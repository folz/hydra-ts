// Regenerates src/glsl/transformDefinitions.ts from the hydra-synth
// devDependency so that every transform definition (name, type, inputs,
// defaults, and glsl body) stays byte-identical to upstream.
//
// Usage: node scripts/generate-transform-definitions.mjs
//
// After bumping the hydra-synth devDependency, re-run this script and review
// the diff. The equivalence test suite verifies the output of this script
// against upstream at test time, so drift fails CI rather than going unseen.

import glslFunctions from 'hydra-synth/src/glsl/glsl-functions.js';
import { writeFileSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, '..', 'src', 'glsl', 'transformDefinitions.ts');
const upstreamVersion = JSON.parse(
  readFileSync(join(here, '..', 'node_modules', 'hydra-synth', 'package.json')),
).version;

const transforms = glslFunctions();

function assertTemplateSafe(name, glsl) {
  if (/[`\\]|\$\{/.test(glsl)) {
    throw new Error(
      `glsl body of '${name}' contains characters unsafe for a template literal`,
    );
  }
}

function emitDefault(value) {
  // JSON.stringify would silently turn NaN into null (the `src` transform's
  // tex input defaults to NaN upstream)
  if (typeof value === 'number' && Number.isNaN(value)) {
    return 'NaN';
  }
  return JSON.stringify(value);
}

function emitInput(input) {
  const lines = [];
  for (const [key, value] of Object.entries(input)) {
    if (key === 'name' || key === 'type') {
      lines.push(`        ${key}: '${value}',`);
    } else if (key === 'default') {
      lines.push(`        default: ${emitDefault(value)},`);
    } else {
      throw new Error(`unexpected input key '${key}' on input ${input.name}`);
    }
  }
  return `      {\n${lines.join('\n')}\n      },`;
}

function emitTransform(transform) {
  assertTemplateSafe(transform.name, transform.glsl);
  const inputs =
    transform.inputs.length === 0
      ? '    inputs: [],'
      : `    inputs: [\n${transform.inputs.map(emitInput).join('\n')}\n    ],`;
  return `  {
    name: '${transform.name}',
    type: '${transform.type}',
${inputs}
    glsl: \`${transform.glsl}\`,
  },`;
}

const generators = transforms.filter((t) => t.type === 'src');
const modifiers = transforms.filter((t) => t.type !== 'src');

const file = `/*
Transform definitions ported from hydra-synth@${upstreamVersion} (src/glsl/glsl-functions.js).

DO NOT EDIT BY HAND. This file is generated by
scripts/generate-transform-definitions.mjs so that every definition stays
byte-identical to upstream, which in turn keeps the compiled fragment shaders
identical to the ones hydra-synth produces. The equivalence test suite
(test/equivalence) asserts this property against the hydra-synth
devDependency.

For each entry, hydra generates a glsl function and a javascript function with
the same name. The 'type' field determines the implicit arguments the glsl
function receives (see processGlsl in createGenerators.ts):

  src:          vec4 fn(vec2 _st, ...inputs)
  coord:        vec2 fn(vec2 _st, ...inputs)
  color:        vec4 fn(vec4 _c0, ...inputs)
  combine:      vec4 fn(vec4 _c0, vec4 _c1, ...inputs)
  combineCoord: vec2 fn(vec2 _st, vec4 _c0, ...inputs)
*/

import { Texture2D } from 'regl';

export type TransformDefinitionType =
  | 'src'
  | 'coord'
  | 'color'
  | 'combine'
  | 'combineCoord';

export type TransformDefinitionInputTypeFloat = {
  type: 'float';
  default?:
    | number
    | number[]
    | ((context: any, props: any) => number | number[]);
};

export type TransformDefinitionInputTypeSampler2D = {
  type: 'sampler2D';
  default?: Texture2D | number;
};

export type TransformDefinitionInputTypeVec4 = {
  type: 'vec4';
  default?: string | number;
};

export type TransformDefinitionInputUnion =
  | TransformDefinitionInputTypeFloat
  | TransformDefinitionInputTypeSampler2D
  | TransformDefinitionInputTypeVec4;

export type TransformDefinitionInput = TransformDefinitionInputUnion & {
  name: string;
};

export interface TransformDefinition {
  name: string;
  type: TransformDefinitionType;
  inputs: readonly TransformDefinitionInput[];
  glsl: string;
}

export interface ProcessedTransformDefinition extends TransformDefinition {
  processed: true;
}

export const generatorTransforms: readonly TransformDefinition[] = [
${generators.map(emitTransform).join('\n')}
];

export const modifierTransforms: readonly TransformDefinition[] = [
${modifiers.map(emitTransform).join('\n')}
];
`;

writeFileSync(outPath, file);
console.log(
  `wrote ${outPath} from hydra-synth@${upstreamVersion}: ` +
    `${generators.length} generators, ${modifiers.length} modifiers`,
);
